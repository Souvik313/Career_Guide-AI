def load_predictions() -> list[dict]:
    """
    Load recommendation predictions generated by
    the recommendation runner.

    Returns:
        list[dict]:
            List containing prediction results for
            all evaluation resumes.

    Raises:
        FileNotFoundError:
            If predictions.json does not exist.
    """

    if not PREDICTIONS_FILE.exists():
        raise FileNotFoundError(
            f"Prediction file not found: {PREDICTIONS_FILE}"
        )

    with open(
        PREDICTIONS_FILE,
        "r",
        encoding="utf-8",
    ) as file:

        predictions = json.load(file)

    logging.info(
        "Loaded predictions for %d resumes.",
        len(predictions),
    )

    return predictions

def build_ground_truth_lookup(
    ground_truth: pd.DataFrame,
) -> dict[str, dict]:
    """
    Build a lookup dictionary from the ground truth dataframe.

    Args:
        ground_truth (pd.DataFrame):
            Ground truth benchmark dataframe.

    Returns:
        dict[str, dict]:
            Mapping from Resume_ID to the corresponding record.
    """

    lookup = {}

    for _, row in ground_truth.iterrows():

        record = row.to_dict()

        lookup[record["Resume_ID"]] = record

    logging.info(
        "Built ground truth lookup for %d resumes.",
        len(lookup),
    )

    return lookup

def infer_domain_from_predictions(
    recommendations: list[str],
) -> str:
    """
    Infer the dominant career domain from the
    recommended job titles.

    Args:
        recommendations (list[str]):
            Top recommended job titles.

    Returns:
        str:
            Predicted career domain.
            Returns "Unknown" if no domain
            can be inferred.
    """

    domain_scores = {
        domain: 0
        for domain in DOMAIN_KEYWORDS
    }

    for recommendation in recommendations:

        title = recommendation.lower()

        for domain, keywords in DOMAIN_KEYWORDS.items():

            for keyword in keywords:

                if keyword in title:
                    domain_scores[domain] += 1

    predicted_domain = max(
        domain_scores,
        key=domain_scores.get,
    )

    if domain_scores[predicted_domain] == 0:
        return "Unknown"

    return predicted_domain

def evaluate_resume(
    prediction: dict,
    ground_truth_lookup: dict[str, dict],
) -> dict:
    """
    Evaluate recommendation quality for a single resume.

    Args:
        prediction (dict):
            Prediction record generated by the recommendation runner.

        ground_truth_lookup (dict[str, dict]):
            Lookup dictionary mapping Resume_ID to its
            corresponding ground truth record.

    Returns:
        dict:
            Resume evaluation containing the calculated metrics.

    Raises:
        KeyError:
            If the Resume_ID is not found in the ground truth.
    """

    resume_id = prediction["resume_id"]

    if resume_id not in ground_truth_lookup:
        raise KeyError(
            f"Resume '{resume_id}' not found in ground truth."
        )

    ground_truth = ground_truth_lookup[resume_id]

    expected_titles = [
        ground_truth["Expected_Role_1"],
        ground_truth["Expected_Role_2"],
        ground_truth["Expected_Role_3"],
        ground_truth["Expected_Role_4"],
        ground_truth["Expected_Role_5"],
    ]

    predicted_titles = prediction["recommendations"]

    expected_domain = ground_truth["Primary_Domain"]

    predicted_domain = infer_domain_from_predictions(
        predicted_titles,
    )

    metrics = calculate_all_metrics(
        predicted_titles=predicted_titles,
        expected_titles=expected_titles,
        predicted_domain=predicted_domain,
        expected_domain=expected_domain,
    )

    return {
        "resume_id": resume_id,
        "expected_domain": expected_domain,
        "predicted_domain": predicted_domain,
        **metrics,
    }

def aggregate_results(
    evaluation_results: list[dict],
) -> dict:
    """
    Aggregate evaluation metrics across all benchmark resumes.

    Args:
        evaluation_results (list[dict]):
            Resume-level evaluation results.

    Returns:
        dict:
            Dataset-level average evaluation metrics.
    """

    total_resumes = len(evaluation_results)

    summary = {
        "total_resumes": total_resumes,
        "precision_at_5": 0.0,
        "recall_at_5": 0.0,
        "mean_reciprocal_rank": 0.0,
        "hit_rate": 0.0,
        "top1_accuracy": 0.0,
        "top3_accuracy": 0.0,
        "domain_accuracy": 0.0,
    }

    for result in evaluation_results:

        summary["precision_at_5"] += result["precision_at_5"]
        summary["recall_at_5"] += result["recall_at_5"]
        summary["mean_reciprocal_rank"] += result["reciprocal_rank"]
        summary["hit_rate"] += result["hit_rate"]
        summary["top1_accuracy"] += result["top1_accuracy"]
        summary["top3_accuracy"] += result["top3_accuracy"]
        summary["domain_accuracy"] += result["domain_accuracy"]

    for metric in (
        "precision_at_5",
        "recall_at_5",
        "mean_reciprocal_rank",
        "hit_rate",
        "top1_accuracy",
        "top3_accuracy",
        "domain_accuracy",
    ):
        summary[metric] /= total_resumes

    logging.info(
        "Aggregated evaluation results for %d resumes.",
        total_resumes,
    )

    return summary

def save_results(
    summary: dict,
    evaluation_results: list[dict],
) -> None:
    """
    Save evaluation results to a JSON file.

    Args:
        summary (dict):
            Aggregated evaluation metrics.

        evaluation_results (list[dict]):
            Resume-level evaluation results.
    """

    output = {
        "summary": summary,
        "resume_results": evaluation_results,
    }

    OUTPUT_FILE.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with open(
        OUTPUT_FILE,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            output,
            file,
            indent=4,
            ensure_ascii=False,
        )

    logging.info(
        "Evaluation results saved to %s",
        OUTPUT_FILE,
    )

def main() -> None:
    """
    Run the complete evaluation pipeline.
    """

    logging.info("-" * 60)
    logging.info("CareerCompass-AI Evaluation Pipeline")
    logging.info("-" * 60)

    predictions = load_predictions()

    ground_truth = load_ground_truth()

    ground_truth_lookup = build_ground_truth_lookup(
        ground_truth,
    )

    evaluation_results = []

    for prediction in predictions:

        result = evaluate_resume(
            prediction=prediction,
            ground_truth_lookup=ground_truth_lookup,
        )

        evaluation_results.append(result)

    summary = aggregate_results(
        evaluation_results,
    )

    save_results(
        summary=summary,
        evaluation_results=evaluation_results,
    )

    logging.info("-" * 60)
    logging.info("Evaluation Summary")
    logging.info("-" * 60)

